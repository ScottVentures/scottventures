// Footer column titles are identical and in the same order on every
// page, so they're translated by position rather than needing a
// data-i18n attribute hand-added to 39 files.
var SV_FOOTER_TITLE_ORDER = ['Product', 'Resources', 'Solutions', 'Legal', 'Company'];

function svGetLang() {
  try {
    return localStorage.getItem('sv_lang') || 'en';
  } catch (e) {
    return 'en';
  }
}

function svSetLang(lang) {
  try {
    localStorage.setItem('sv_lang', lang);
  } catch (e) {
    /* ignore */
  }
}

// Replaces only the first non-empty text node inside `el`, so any
// nested element (an icon, a badge, a screen-reader span) survives.
function svSetLinkText(el, text) {
  for (var i = 0; i < el.childNodes.length; i++) {
    var node = el.childNodes[i];
    if (node.nodeType === 3 && node.textContent.trim()) {
      node.textContent = text;
      return;
    }
  }
  if (!el.textContent.trim()) {
    el.textContent = text;
  }
}

function svApplyLang(lang) {
  var dict = SV_TRANSLATIONS[lang] || SV_TRANSLATIONS.en;

  // Header nav links.
  document.querySelectorAll('.nav-link[href]').forEach(function (link) {
    // The Account link's href points at the login page (or wherever the
    // visitor lands), which isn't in SV_HREF_KEY — it's translated by id
    // instead. Once logged in, sources/js/session.js replaces this whole
    // element with the avatar button, so this branch only ever applies
    // to the logged-out "Account" link.
    if (link.id === 'accountNavLink') {
      svSetLinkText(link, dict.Account);
      return;
    }
    var href = link.getAttribute('href');
    var key = SV_HREF_KEY[href];
    if (key && dict[key]) {
      svSetLinkText(link, dict[key]);
    }
  });

  // Footer: column titles, translated by position.
  document.querySelectorAll('.footer-main__title').forEach(function (el, index) {
    var key = SV_FOOTER_TITLE_ORDER[index];
    if (key && dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Footer: link labels, translated by href (scoped to the footer so it
  // never touches the header nav's own translation pass above).
  document.querySelectorAll('.footer-main__nav a[href]').forEach(function (a) {
    var href = a.getAttribute('href');
    var key = SV_FOOTER_HREF_KEY[href];
    if (key && dict[key]) {
      svSetLinkText(a, dict[key]);
    }
  });

  // Shared CTA buttons / links that repeat across many pages (article,
  // tutorial, and material cards all reuse the same "Read More" button,
  // for example) but aren't tied to a single href the way nav/footer
  // links are, so they're matched by their original English text
  // instead. The original text is cached on the element (data-i18n-src)
  // the first time it's seen, so repeated language switches always
  // translate from the true original rather than from whatever the
  // previous language left behind.
  document.querySelectorAll('.filled-button').forEach(function (el) {
    var original = el.getAttribute('data-i18n-src');
    if (!original) {
      original = (el.textContent || '').trim();
      if (!original) return;
      el.setAttribute('data-i18n-src', original);
    }
    if (dict[original]) {
      svSetLinkText(el, dict[original]);
    }
  });

  // Form fields (contact form, login) translated by their original
  // English placeholder text, cached the same way as above.
  document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(function (el) {
    var original = el.getAttribute('data-i18n-src');
    if (!original) {
      original = el.getAttribute('placeholder') || '';
      if (!original) return;
      el.setAttribute('data-i18n-src', original);
    }
    if (dict[original]) {
      el.setAttribute('placeholder', dict[original]);
    }
  });

  // Account dropdown items (sources/js/session.js renders these with
  // data-i18n attributes once the visitor is logged in) plus anything
  // else on the page that opts in with data-i18n the same way.
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Update the "Current language" label in every footer switcher on
  // the page.
  document.querySelectorAll('.lang__current').forEach(function (el) {
    var textNode = null;
    for (var i = 0; i < el.childNodes.length; i++) {
      if (el.childNodes[i].nodeType === 3 && el.childNodes[i].textContent.trim()) {
        textNode = el.childNodes[i];
        break;
      }
    }
    if (textNode) {
      textNode.textContent = ' ' + (dict.English || 'English') + ' ';
    }
  });
}
// Exposed on window explicitly (in addition to the implicit global from
// the function declaration) so other scripts, like session.js, can
// check `typeof window.svApplyLang` before calling it.
window.svApplyLang = svApplyLang;
window.svGetLang = svGetLang;
window.svSetLang = svSetLang;

document.addEventListener('DOMContentLoaded', function () {
  // Click-to-open/close, in addition to the existing hover behavior —
  // needed for touch devices where :hover never fires.
  document.querySelectorAll('.footer-big__lang').forEach(function (wrap) {
    var current = wrap.querySelector('.lang__current');
    var menu = wrap.querySelector('.lang__menu');
    if (!current || !menu) return;

    current.addEventListener('click', function (e) {
      e.preventDefault();
      e.stopPropagation();
      var isOpen = menu.style.display === 'block';
      document.querySelectorAll('.lang__menu').forEach(function (m) { m.style.display = 'none'; });
      menu.style.display = isOpen ? 'none' : 'block';
    });

    // Real language switching: intercept clicks on the languages we
    // support, apply the translation instead of navigating to a
    // dead route. Unsupported languages just close the menu.
    menu.querySelectorAll('a[href]').forEach(function (a) {
      var href = a.getAttribute('href') || '';
      var langCode = href.replace(/^\//, '') || 'en';
      a.addEventListener('click', function (e) {
        e.preventDefault();
        if (SV_SUPPORTED_LANGS.indexOf(langCode) !== -1) {
          svSetLang(langCode);
          svApplyLang(langCode);
        }
        menu.style.display = 'none';
      });
    });
  });

  document.addEventListener('click', function () {
    document.querySelectorAll('.lang__menu').forEach(function (m) { m.style.display = 'none'; });
  });

  var savedLang = svGetLang();
  if (savedLang !== 'en') {
    svApplyLang(savedLang);
  }
});
