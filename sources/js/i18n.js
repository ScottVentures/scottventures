// `.lang__current` / `.lang__menu`) and opens on hover via CSS, but every
// language link pointed at a route that doesn't exist on this site (/es,
// /fr, /de, ...) — clicking one just navigated to a dead page, and only
// Spanish, French, and German actually had translations wired up, so
// every other listed language silently did nothing. This file intercepts
// those clicks, applies real in-page translations for all 26 listed
// languages, remembers the choice, and closes the menu.
//
